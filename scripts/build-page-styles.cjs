// Combine existing styles without changing their order, selectors or media queries.
// Root-relative CSS files stay at the root, so their asset URLs keep working.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
function buildPageStyles({check = false} = {}) {
  const manifest = JSON.parse(fs.readFileSync(path.join(__dirname, 'page-styles.json'), 'utf8'));
  const stale = [];
  for (const [page, styles] of Object.entries(manifest)) {
    const bundle = `page-${path.basename(page, '.html')}.bundle.css`;
    const css = '/* Generated by scripts/build-page-styles.cjs; edit the source styles. */\n' + styles.map(({file, media}) => {
      if (path.basename(file) !== file || !file.endsWith('.css')) throw new Error('Only root CSS sources are supported');
      const source = fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n');
      if (/@import\b|@charset\b/.test(source)) throw new Error(`Unsupported CSS import in ${file}`);
      return `/* ${file} */\n` + (media ? `@media ${media} {\n${source}\n}\n` : source + '\n');
    }).join('\n').trimEnd() + '\n';
    const hash = crypto.createHash('sha256').update(css).digest('hex').slice(0, 12);
    const link = `<link rel="stylesheet" href="./${bundle}?v=${hash}" />`;
    const html = fs.readFileSync(path.join(root, page), 'utf8').replace(/\r\n/g, '\n');
    let inserted = false;
    const next = html.replace(/<link\b[^>]*\brel="stylesheet"[^>]*>/g, tag => {
      const href = tag.match(/href="([^"]+)"/)?.[1];
      const file = href?.replace(/^\.\//, '').split('?')[0];
      if (file !== bundle && !styles.some(style => style.file === file)) return tag;
      if (inserted) return '';
      inserted = true;
      return link;
    }).replace(/^[ \t]+\r?\n/gm, '').trimEnd() + '\n';
    if (!inserted) throw new Error(`Missing stylesheet entry point in ${page}`);
    for (const [file, content] of [[bundle, css], [page, next]]) {
      const target = path.join(root, file);
      if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== content) {
        stale.push(file);
        if (!check) fs.writeFileSync(target, content);
      }
    }
  }
  if (check && stale.length) throw new Error(`Generated styles are stale: ${stale.join(', ')}. Run npm run assets:styles.`);
  return stale;
}
module.exports = {buildPageStyles};
if (require.main === module) {
  const changes = buildPageStyles({check:process.argv.includes('--check')});
  console.log(`Page styles ${process.argv.includes('--check') ? 'verified' : 'generated'} (${changes.length} changes)`);
}
