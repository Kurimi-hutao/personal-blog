"""Subset static headings and bounded fallback blocks, retaining every original glyph."""
from pathlib import Path
from html.parser import HTMLParser
from fontTools.merge import Merger
from fontTools import subset
from fontTools.ttLib import TTFont
import re
import io
from collections import defaultdict

root = Path(__file__).resolve().parents[1]

class Headings(HTMLParser):
    def __init__(self):
        super().__init__()
        self.depth = 0
        self.active = []
        self.characters = set()
    def handle_starttag(self, tag, attrs):
        if tag in ('meta', 'link', 'img', 'input', 'source', 'br', 'hr', 'wbr'): return
        enabled = tag in ('h1', 'h2', 'h3', 'h4', 'title') or any(
            name == 'class' and any(part in value.split() for part in ('brand-name', 'eyebrow')) for name, value in attrs if value)
        self.active.append((tag, enabled))
    def handle_endtag(self, tag):
        for index in range(len(self.active) - 1, -1, -1):
            if self.active[index][0] == tag:
                del self.active[index:]
                break
    def handle_data(self, data):
        if any(enabled for _, enabled in self.active): self.characters.update(map(ord, data))

parser = Headings()
for file in root.glob('*.html'):
    parser.feed(file.read_text(encoding='utf-8'))
    parser.active.clear()
for text in re.findall(r'\btitle:\s*"([^"]+)"', (root / 'works-data.js').read_text(encoding='utf-8')):
    parser.characters.update(map(ord, text))
for file in root.glob('*.css'):
    if '.bundle.' not in file.name:
        for text in re.findall(r'content:\s*[\'"]([^\'"{}]+)[\'"]', file.read_text(encoding='utf-8')):
            parser.characters.update(map(ord, text))

sources = sorted((root / 'assets/fonts/blog-brush').glob('*400-normal.woff2'))
supported = set()
for source in sources:
    with TTFont(source) as face: supported.update(face.getBestCmap())
characters = (parser.characters | set(range(32, 127))) & supported
font = Merger().merge([str(source) for source in sources])
full = io.BytesIO()
font.save(full)
full_bytes = full.getvalue()
original_cmap = font.getBestCmap()
original_widths = {code: font['hmtx'][name][0] for code, name in original_cmap.items()}
options = subset.Options()
subsetter = subset.Subsetter(options=options)
subsetter.populate(unicodes=characters)
subsetter.subset(font)
font.flavor = 'woff2'
output = root / 'assets/fonts/blog-brush-core.woff2'
font.save(output)

# Split sparse historical font shards into bounded Unicode blocks. An unknown
# article title then downloads only its glyph blocks, with every old glyph kept.
blocks = defaultdict(set)
for code in supported: blocks[code // 64].add(code)
directory = root / 'assets/fonts/blog-brush-slim'
directory.mkdir(exist_ok=True)
faces = []
verified = set()
for index, (block, codes) in enumerate(sorted(blocks.items())):
    face = TTFont(io.BytesIO(full_bytes))
    part = subset.Subsetter(options=subset.Options())
    part.populate(unicodes=codes)
    part.subset(face)
    cmap = face.getBestCmap()
    assert set(cmap) == codes
    assert all(face['hmtx'][name][0] == original_widths[code] for code, name in cmap.items())
    verified.update(cmap)
    face.flavor = 'woff2'
    name = f'brush-{block * 64:04x}.woff2'
    face.save(directory / name)
    faces.append('@font-face{font-family:"Blog Brush";font-style:normal;font-display:swap;font-weight:400;'
                 f'src:url("./assets/fonts/blog-brush-slim/{name}") format("woff2");'
                 f'unicode-range:U+{min(codes):X}-{max(codes):X};' + '}')
    if index % 50 == 0: print(f'Brush blocks: {index + 1}/{len(blocks)}', flush=True)
assert verified == supported
compact = '\n'.join(faces)
# The core face is last and wins for the existing static UI's common glyphs.
core = '@font-face{font-family:"Blog Brush";font-style:normal;font-display:swap;font-weight:400;src:url("./assets/fonts/blog-brush-core.woff2") format("woff2");unicode-range:'
core += ','.join(f'U+{code:X}' for code in sorted(characters)) + ';}'
(root / 'fonts-headings.css').write_text('/* Generated by scripts/build-brush-core.py; all original glyphs retained in bounded blocks. */\n' + compact + '\n' + core + '\n', encoding='utf-8')
print(f'Brush core: {len(characters)} glyphs, {output.stat().st_size} bytes; {len(verified)} original glyphs verified in {len(blocks)} blocks')
