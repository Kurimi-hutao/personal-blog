"""Build small header avatars and a compact, heading-only webfont stylesheet."""
from pathlib import Path
import re
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
with Image.open(ROOT / 'assets/brand-tigerhat.png') as image:
    for size in (88, 132):
        avatar = image.convert('RGBA')
        avatar.thumbnail((size, size), Image.Resampling.LANCZOS)
        avatar.save(ROOT / f'assets/brand-tigerhat-{size}.webp', quality=86, method=6)

# Keep the original stylesheet as the source; only brush headings need downloads.
source = (ROOT / 'fonts.css').read_text(encoding='utf-8')
faces = re.findall(r'@font-face\s*\{[^}]+\}', source)
faces = [face for face in faces if '"Blog Brush"' in face and 'unicode-range:' in face]
compact = re.sub(r'\s+', ' ', '\n'.join(faces))
compact = re.sub(r'\s*([{}:;,])\s*', r'\1', compact)
(ROOT / 'fonts-headings.css').write_text('/* Generated by scripts/optimize-blog-assets.py */\n' + compact + '\n', encoding='utf-8')
